"""Render the three COCO lmms-eval task YAMLs (one per prompt) into tasks/pope_custom/.

Usage (inside WSL, from the project folder; rerun on every machine, since the YAMLs hold
the local absolute path of the frozen question file):
    python src/make_task_yamls_coco.py

COCO-only version of make_task_yamls.py. Task names: pope_coco_{ordinary,neutral,evidence}.
Decoding is greedy with the shared MAX_NEW_TOKENS from src/prompts.py, so token budgets are
matched across prompt formats.
"""
from pathlib import Path

from prompts import MAX_NEW_TOKENS, PROMPTS

PROJECT = Path(__file__).resolve().parents[1]
TASK_DIR = PROJECT / "tasks/pope_custom"
DATA_FILE = PROJECT / "data/eval_sets/coco_pope.jsonl"

TEMPLATE = """\
# GENERATED by src/make_task_yamls_coco.py; do not edit by hand (rerun the script instead).
task: "pope_coco_{prompt}"
dataset_path: json
dataset_kwargs:
  data_files:
    test: "{data_file}"
test_split: test
output_type: generate_until
doc_to_visual: !function utils.pope_doc_to_visual
doc_to_text: !function utils.doc_to_text_{prompt}
doc_to_target: "answer"
generation_kwargs:
  max_new_tokens: {max_new_tokens}
  temperature: 0
  top_p: 1.0
  num_beams: 1
  do_sample: false
process_results: !function utils.pope_process_results
metric_list:
{metrics}
metadata:
  - version: 1.0
"""
METRICS = ["accuracy", "precision", "recall", "f1_score", "specificity",
           "hallucination_rate", "abstention_rate", "yes_ratio"]
LOWER_IS_BETTER = {"hallucination_rate"}


def main():
    if not DATA_FILE.exists():
        raise SystemExit(f"missing {DATA_FILE}; build the COCO eval set first")
    metrics = "\n".join(
        f"  - metric: pope_{m}\n"
        f"    aggregation: !function utils.pope_aggregate_{m}\n"
        f"    higher_is_better: {'false' if m in LOWER_IS_BETTER else 'true'}"
        for m in METRICS)
    for prompt in PROMPTS:
        out = TASK_DIR / f"pope_coco_{prompt}.yaml"
        out.write_text(TEMPLATE.format(prompt=prompt, data_file=DATA_FILE, max_new_tokens=MAX_NEW_TOKENS,
                                       metrics=metrics), newline="\n")
        print(f"wrote {out.relative_to(PROJECT)}")


if __name__ == "__main__":
    main()
