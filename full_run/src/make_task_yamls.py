"""Render the six lmms-eval task YAMLs (2 datasets x 3 prompts) into tasks/pope_custom/.

Usage (inside WSL, from the project folder; rerun on every machine, since the YAMLs hold
the local absolute path of the frozen question files):
    python src/make_task_yamls.py

Task names: pope_{coco,gqa}_{ordinary,neutral,evidence}. Decoding is greedy with the shared
MAX_NEW_TOKENS from src/prompts.py, so token budgets are matched across prompt formats.
"""
from pathlib import Path

from prompts import MAX_NEW_TOKENS, PROMPTS

PROJECT = Path(__file__).resolve().parents[1]
TASK_DIR = PROJECT / "tasks/pope_custom"
DATASETS = ["coco", "gqa"]

TEMPLATE = """\
# GENERATED by src/make_task_yamls.py; do not edit by hand (rerun the script instead).
task: "pope_{dataset}_{prompt}"
dataset_path: json
dataset_kwargs:
  data_files:
    test: "{data_file}"
test_split: test
output_type: generate_until
doc_to_visual: !function utils.pope_doc_to_visual
doc_to_text: !function utils.doc_to_text_{prompt}
doc_to_target: "answer"
generation_kwargs:
  max_new_tokens: {max_new_tokens}
  temperature: 0
  top_p: 1.0
  num_beams: 1
  do_sample: false
process_results: !function utils.pope_process_results
metric_list:
{metrics}
metadata:
  - version: 1.0
"""
METRICS = ["accuracy", "precision", "recall", "f1_score", "specificity",
           "hallucination_rate", "abstention_rate", "yes_ratio"]
LOWER_IS_BETTER = {"hallucination_rate"}


def main():
    metrics = "\n".join(
        f"  - metric: pope_{m}\n"
        f"    aggregation: !function utils.pope_aggregate_{m}\n"
        f"    higher_is_better: {'false' if m in LOWER_IS_BETTER else 'true'}"
        for m in METRICS)
    for dataset in DATASETS:
        data_file = PROJECT / f"data/eval_sets/{dataset}_pope.jsonl"
        if not data_file.exists():
            raise SystemExit(f"missing {data_file}; build and freeze the eval sets first")
        for prompt in PROMPTS:
            out = TASK_DIR / f"pope_{dataset}_{prompt}.yaml"
            out.write_text(TEMPLATE.format(dataset=dataset, prompt=prompt, data_file=data_file,
                                           max_new_tokens=MAX_NEW_TOKENS, metrics=metrics),
                           newline="\n")
            print(f"wrote {out.relative_to(PROJECT)}")


if __name__ == "__main__":
    main()
