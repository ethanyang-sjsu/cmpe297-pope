"""Compare the built COCO set with the teammate's archived POPE file (consistency check).

Usage (inside WSL, conda env cmpe297, from the project folder):
    python src/compare_with_teammate_set.py

Inputs:  data/eval_sets/coco_pope.jsonl, archive/pope_val2017.jsonl, COCO val2017 annotations
Output:  results/tables/teammate_set_comparison.md   report table + label checks of the old file

Questions are compared position by position within each (image, split): POPE writes each
positive followed by its paired negative, so position i in one file corresponds to
position i in the other.
"""
import argparse
import json
import os
import re
from collections import Counter
from pathlib import Path

from build_pope_coco import load_coco
from pope_sampling import SPLITS

PROJECT = Path(__file__).resolve().parents[1]
QUESTION_RE = re.compile(r"^Is there (an?) (.+?) in the (\w+)\?$")


def read_jsonl(path):
    with open(path) as fh:
        return [json.loads(line) for line in fh if line.strip()]


def parse_old(row):
    """Return (article, object, image_word) from the teammate's question text, or None."""
    m = QUESTION_RE.match(row["question"].strip())
    return m.groups() if m else None


def group(rows):
    out = {}
    for r in rows:
        out.setdefault((r["image"], r["category"]), []).append(r)
    return out


def pct(a, b):
    return f"{a:,}/{b:,} ({100 * a / b:.1f}%)" if b else "0/0"


def rel(path) -> str:
    """Project-relative path with forward slashes, for the Markdown output."""
    return os.path.relpath(path, PROJECT).replace(os.sep, "/")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-root", default=os.environ.get("CMPE297_DATA", os.path.expanduser("~/cmpe297/data")))
    ap.add_argument("--new", default=str(PROJECT / "data/eval_sets/coco_pope.jsonl"))
    ap.add_argument("--old", default=str(PROJECT / "archive/pope_val2017.jsonl"))
    ap.add_argument("--out-md", default=str(PROJECT / "results/tables/teammate_set_comparison.md"))
    args = ap.parse_args()

    new, old = read_jsonl(args.new), read_jsonl(args.old)
    _, vocab, present, _ = load_coco(os.path.join(args.data_root, "coco/annotations/instances_val2017.json"))

    # --- parse the old question text ---
    unparsed = [r for r in old if parse_old(r) is None]
    if unparsed:
        raise SystemExit(f"{len(unparsed)} old questions do not match {QUESTION_RE.pattern}, "
                         f"e.g. {unparsed[0]['question']!r}")
    for r in old:
        art, obj, word = parse_old(r)
        r["_object"], r["_article"], r["_image_word"] = obj, art, word
    unknown = sorted({r["_object"] for r in old} - set(vocab))

    # --- structure of the old file ---
    old_images = list(dict.fromkeys(r["image"] for r in old))
    new_images = list(dict.fromkeys(r["image"] for r in new))
    old_ids_per_split = Counter(r["category"] for r in old)
    old_unique_ids = len({(r["category"], r["question_id"]) for r in old})
    typo_rows = [r for r in old if r["_image_word"] != "image"]
    bad_article = [r for r in old if r["_article"] != ("an" if r["_object"][0] in "aeiou" else "a")]

    # --- label checks of the old file against COCO annotations ---
    label_issue = Counter()
    issue_examples = []
    for r in old:
        is_present = r["_object"] in present.get(r["image"], [])
        wrong = (r["answer"] == "yes" and not is_present) or (r["answer"] == "no" and is_present)
        if wrong:
            label_issue[r["category"], r["answer"]] += 1
            if len(issue_examples) < 10:
                issue_examples.append(r)

    # --- question-by-question match ---
    g_new, g_old = group(new), group(old)
    same = Counter()
    total = Counter()
    mismatches = []
    for (image, split), new_rows in g_new.items():
        old_rows = g_old.get((image, split), [])
        for i, nr in enumerate(new_rows):
            total[split, nr["answer"]] += 1
            orow = old_rows[i] if i < len(old_rows) else None
            if orow and orow["_object"] == nr["object"] and orow["answer"] == nr["answer"]:
                same[split, nr["answer"]] += 1
            elif split != "random":
                mismatches.append((image, split, i, nr, orow))

    # --- write the report table ---
    lines = [
        "# COCO eval set vs the teammate's pilot file",
        "",
        f"Generated by `src/compare_with_teammate_set.py` from `{rel(args.new)}` (ours) and "
        f"`{rel(args.old)}` (teammate's file, used for the pilot run).",
        "",
        "## Structure",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Rows (ours / theirs) | {len(new):,} / {len(old):,} |",
        f"| Images (ours / theirs) | {len(new_images)} / {len(old_images)} |",
        f"| Same images in the same order | {'yes' if new_images == old_images else 'no'} |",
        f"| Their question IDs unique across splits | no: 1 to {max(old_ids_per_split.values()):,} repeat in each split; "
        f"unique within a split: {'yes' if old_unique_ids == len(old) else 'no'} |",
        f"| Their question text with a typo for \"image\" | {pct(len(typo_rows), len(old))}"
        f" ({', '.join(sorted({repr(r['_image_word']) for r in typo_rows}))}) |",
        f"| Their question text with a wrong a/an | {pct(len(bad_article), len(old))} |",
        f"| Their objects outside the 80 COCO categories | {len(unknown)}{': ' + ', '.join(unknown) if unknown else ''} |",
        "",
        "## Identical questions",
        "",
        "Same image, object and answer at the same position within the image's questions.",
        "",
        "| Split | \"yes\" questions | \"no\" questions |",
        "|---|---|---|",
    ]
    for split in SPLITS:
        lines.append(f"| {split} | {pct(same[split, 'yes'], total[split, 'yes'])} | "
                     f"{pct(same[split, 'no'], total[split, 'no'])} |")
    lines += [
        "",
        "Random-split negatives are expected to differ: they are random draws from a different "
        "random generator. Every other question is chosen deterministically by the POPE rules.",
        "",
    ]
    if mismatches:
        lines += ["Differences outside the random split:", "",
                  "| Image | Split | Position | Ours | Theirs |", "|---|---|---|---|---|"]
        for image, split, i, nr, orow in mismatches:
            theirs = f"{orow['_object']} ({orow['answer']})" if orow else "(missing)"
            lines.append(f"| {image} | {split} | {i + 1} | {nr['object']} ({nr['answer']}) | {theirs} |")
        lines.append("")
    lines += [
        "## Their labels checked against COCO annotations",
        "",
        "A \"yes\" is wrong if the object has no annotation in the image; a \"no\" is wrong if it has one. "
        "This only checks consistency with the annotations; whether annotated absence is real absence "
        "is what the manual audit (step 6) measures.",
        "",
        "| Split | Wrong \"yes\" labels | Wrong \"no\" labels |",
        "|---|---|---|",
    ]
    for split in SPLITS:
        lines.append(f"| {split} | {label_issue[split, 'yes']} | {label_issue[split, 'no']} |")
    if issue_examples:
        lines += ["", "Examples:", ""] + [
            f"- `{r['image']}` {r['category']}: {r['question']!r} labelled {r['answer']}" for r in issue_examples]
    lines.append("")

    md_path = Path(args.out_md)
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text("\n".join(lines), newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
